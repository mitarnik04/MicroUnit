<?php

namespace MicroUnit\Benchmarks;

/** Writes summary.md: one table per project and scenario, plus totals across the corpus. */
final class Report
{
    private function __construct() {}

    /**
     * @param array<string, mixed> $environment
     * @param array<string, array{project: array<string, mixed>, summary: array<string, mixed>, excluded: array<string, string>, versions: array<string, string>}> $results
     * @param array<string, mixed> $options
     */
    public static function markdown(array $environment, array $results, array $options): string
    {
        $machine = $environment['machine'];
        $php = $environment['php'];
        $lines = [
            '# MicroUnit benchmark, ' . substr($environment['capturedAt'], 0, 10),
            '',
            'Generated by `php benchmarks/run.php`. Raw data: `runs.jsonl` (every measured run), `environment.json`, `excluded/`, `outputs/`.',
            '',
            '## Conditions',
            '',
            '| | |',
            '|---|---|',
            '| Machine | ' . ($machine['cpu'] ?? '?') . ', ' . ($machine['cores'] ?? '?') . ' cores / ' . ($machine['logicalProcessors'] ?? '?') . ' threads, ' . round(($machine['memoryBytes'] ?? 0) / 1073741824) . ' GiB RAM |',
            '| OS | ' . ($machine['os'] ?? '?') . ' ' . ($machine['osBuild'] ?? '') . ' |',
            '| Power | ' . ($machine['powerPlan'] ?? $machine['cpuGovernor'] ?? '?') . (isset($machine['onBattery']) ? ($machine['onBattery'] ? ', on battery' : ', on AC power') : '') . ' |',
            '| Antivirus real-time scanning | ' . match ($machine['defenderRealTimeProtection'] ?? null) { true => 'on (Windows Defender)', false => 'off', default => 'unknown' } . ' |',
            '| PHP | ' . $php['version'] . ' (' . $php['build'] . '), OPcache CLI ' . ($php['settings']['opcache.enable_cli'] ? 'on' : 'off') . ', JIT ' . (in_array($php['settings']['opcache.jit'], [false, '', '0', 'disable', 'off'], true) || !$php['settings']['opcache.enable_cli'] ? 'off' : $php['settings']['opcache.jit']) . ', Xdebug ' . (in_array('xdebug', $php['extensions'], true) ? 'loaded' : 'not loaded') . ' |',
            '| MicroUnit | ' . $environment['microunit']['version'] . ' (' . ($environment['microunit']['commit'] === null ? 'uncommitted' : substr($environment['microunit']['commit'], 0, 12)) . ($environment['microunit']['uncommittedChangesInSrc'] ? ', with uncommitted changes' : '') . ', code hash ' . $environment['microunit']['srcSha256'] . ') |',
            '| Method | ' . $options['warmup'] . ' warm-up run(s) per tool (discarded), then ' . $options['runs'] . ' measured round(s); every tool runs once per round, in rotating order. Wall-clock time from process start to exit. Parallel: ' . $options['workers'] . ' workers for every tool. |',
            '',
        ];

        $totals = [];
        foreach ($results as $result) {
            $project = $result['project'];
            $lines[] = "## {$project['name']} {$project['tag']}";
            $lines[] = '';
            $lines[] = "`{$project['repo']}` at `{$project['sha']}`. " . count($result['excluded']) . ' test methods excluded from every tool (see `excluded/' . $project['slug'] . '.json`).';
            $lines[] = '';
            foreach ($result['versions'] as $tool => $version) {
                $lines[] = "- $tool: $version";
            }
            $lines[] = '';
            foreach ($result['summary'] as $scenario => $data) {
                $lines[] = '### ' . Benchmark::SCENARIOS[$scenario];
                $lines[] = '';
                if (!$data['valid']) {
                    $lines[] = '**Not comparable:** the tools ran different numbers of tests (' . json_encode($data['testCounts']) . '); no result is reported.';
                    $lines[] = '';
                    continue;
                }
                $microunit = $data['tools']['microunit']['seconds']['median'] ?? null;
                $lines[] = '| Tool | Tests | Median | p90 | Min | Max | CV | Peak memory (median) | vs. MicroUnit |';
                $lines[] = '|---|---:|---:|---:|---:|---:|---:|---:|---:|';
                foreach ($data['tools'] as $tool => $stats) {
                    $seconds = $stats['seconds'];
                    $ratio = $microunit && $tool !== 'microunit' ? sprintf('%.2f× the time', $seconds['median'] / $microunit) : 'baseline';
                    $lines[] = sprintf(
                        '| %s | %s | %.3f s | %.3f s | %.3f s | %.3f s | %.1f%% | %s | %s |',
                        $tool,
                        $data['testCounts'][$tool] ?? 'n/a',
                        $seconds['median'], $seconds['p90'], $seconds['minimum'], $seconds['maximum'], $seconds['coefficientOfVariation'] * 100,
                        $stats['peakMemoryMiB'] === null ? 'n/a' : sprintf('%.1f MiB', $stats['peakMemoryMiB']['median']),
                        $ratio,
                    );
                    $totals[$scenario][$tool][$project['slug']] = $seconds['median'];
                }
                $lines[] = '';
            }
        }

        $lines[] = '## Totals';
        $lines[] = '';
        $lines[] = 'Sum of medians over the projects where every listed tool produced a comparable result.';
        $lines[] = '';
        foreach ($totals as $scenario => $tools) {
            $common = array_values(array_intersect(...array_map(array_keys(...), array_values($tools))));
            $lines[] = '### ' . Benchmark::SCENARIOS[$scenario] . ' (' . count($common) . ' projects)';
            $lines[] = '';
            $lines[] = '| Tool | Total | vs. MicroUnit |';
            $lines[] = '|---|---:|---:|';
            $microunitTotal = isset($tools['microunit']) ? array_sum(array_intersect_key($tools['microunit'], array_flip($common))) : null;
            foreach ($tools as $tool => $perProject) {
                $total = array_sum(array_intersect_key($perProject, array_flip($common)));
                $lines[] = sprintf('| %s | %.2f s | %s |', $tool, $total, $microunitTotal && $tool !== 'microunit' ? sprintf('%.2f×', $total / $microunitTotal) : 'baseline');
            }
            $lines[] = '';
        }

        return implode("\n", $lines) . "\n";
    }
}
