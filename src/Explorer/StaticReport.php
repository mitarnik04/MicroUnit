<?php

namespace MicroUnit\Explorer;

use MicroUnit\Helpers\HtmlAssets;

/**
 * Renders a finished run as a single, self-contained HTML document: the verdict first, then every
 * reject with its reason, then the full channel list. No JavaScript, so it works as a CI artifact,
 * in mail clients' previews and on paper.
 *
 * @phpstan-import-type Report from ExplorerReport
 * @phpstan-import-type TestEntry from ExplorerReport
 * @phpstan-import-type AssertionDetails from ExplorerReport
 */
final class StaticReport
{
    private const array VERDICTS = ['passed' => 'Pass', 'failed' => 'Reject', 'skipped' => 'Skipped'];

    private function __construct() {}

    /** @param Report $report as built by ExplorerReport */
    public static function render(array $report): string
    {
        $summary = $report['summary'];
        $tests = array_merge(...array_map(static fn(array $suite): array => $suite['tests'], $report['suites']));
        $rejects = array_values(array_filter($tests, static fn(array $test): bool => $test['status'] === 'failed'));
        $skipped = array_values(array_filter($tests, static fn(array $test): bool => $test['status'] === 'skipped'));

        $body = self::head($report)
            . self::verdict($summary, (float) $report['durationSeconds'])
            . ($rejects === [] ? '' : self::section('Rejects', count($rejects), implode('', array_map(self::rejectCard(...), $rejects))))
            . ($skipped === [] ? '' : self::section('Skipped', count($skipped), self::skippedList($skipped)))
            . self::section('All channels', count($tests), implode('', array_map(self::suiteTable(...), $report['suites'])))
            . '<footer>Generated by MicroUnit ' . HtmlAssets::escape($report['environment']['microunit']) . ' on PHP ' . HtmlAssets::escape($report['environment']['php']) . '.</footer>';

        $title = ($summary['failed'] > 0 ? "{$summary['failed']} rejected" : 'All pass') . ' · Test report';

        return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
            . '<title>' . HtmlAssets::escape($title) . '</title>'
            . '<link rel="icon" href="' . HtmlAssets::faviconDataUri($summary['failed'] > 0 ? '#FF6A6F' : '#3DDC84') . '">'
            . '<style>' . HtmlAssets::baseStyles() . "\n" . HtmlAssets::resource('report.css') . '</style></head>'
            . "<body><main class=\"sheet\">$body</main></body></html>";
    }

    /** @param Report $report */
    private static function head(array $report): string
    {
        $finishedAt = date('Y-m-d H:i', strtotime((string) $report['finishedAt']) ?: time());
        $framework = $report['environment']['framework'] ?? null;

        return '<header class="sheet-head"><div class="brand">' . HtmlAssets::mark()
            . '<div><div class="wordmark">microunit</div><div class="label">Test report</div></div></div>'
            . '<div class="meta">Finished ' . HtmlAssets::escape($finishedAt) . '<br>PHP ' . HtmlAssets::escape($report['environment']['php'])
            . ($framework === null ? '' : ' · ' . HtmlAssets::escape($framework)) . '</div></header>';
    }

    /** @param array{total: int, passed: int, failed: int, skipped: int, notrun: int} $summary */
    private static function verdict(array $summary, float $seconds): string
    {
        $isPass = $summary['failed'] === 0;
        $time = $seconds >= 1 ? number_format($seconds, 2) . '<small>s</small>' : number_format($seconds * 1000, 0) . '<small>ms</small>';

        return '<section class="verdict-row">'
            . '<div class="verdict ' . ($isPass ? 'pass' : 'reject') . '">' . ($isPass ? 'Pass' : 'Reject') . '</div>'
            . '<div class="readout">'
            . self::value((string) $summary['passed'], 'Pass', 'pass')
            . self::value((string) $summary['failed'], 'Reject', $summary['failed'] > 0 ? 'reject' : '')
            . ($summary['skipped'] > 0 ? self::value((string) $summary['skipped'], 'Skip', 'skip') : '')
            . self::value((string) $summary['total'], 'Channels', '')
            . self::value($time, 'Run time', '')
            . '</div></section>';
    }

    private static function value(string $value, string $label, string $class): string
    {
        return "<div><div class=\"value $class\">$value</div><span class=\"label\">$label</span></div>";
    }

    private static function section(string $title, int $count, string $content): string
    {
        return '<section class="block"><h2>' . HtmlAssets::escape($title) . "<span class=\"count\">$count</span></h2>$content</section>";
    }

    /** @param TestEntry $test */
    private static function rejectCard(array $test): string
    {
        $failure = $test['failure'];
        $where = $test['file'] === null ? '' : $test['file'] . ':' . ($test['failureLine'] ?? $test['line']);

        $details = match (true) {
            $failure === null => '',
            $failure['kind'] === 'error' => '<div class="message">' . HtmlAssets::escape($failure['class'] . ': ' . $failure['message']) . '</div>'
                . '<pre class="block">' . HtmlAssets::escape($failure['file'] . ':' . $failure['line'] . "\n" . $failure['trace']) . '</pre>',
            default => self::assertionDetails($failure),
        };
        $output = $test['output'] === null ? '' : '<pre class="block">' . HtmlAssets::escape($test['output']) . '</pre>';

        return '<article class="reject-card"><div class="title"><span class="ch">' . self::channel($test['channel']) . '</span>'
            . '<h3>' . HtmlAssets::escape($test['suite'] . ' › ' . $test['name']) . '</h3></div>'
            . '<div class="where">' . HtmlAssets::escape($where) . '</div>'
            . $details . $output . '</article>';
    }

    /** @param AssertionDetails $failure */
    private static function assertionDetails(array $failure): string
    {
        $html = ($failure['customMessage'] === null ? '' : '<div class="custom">' . HtmlAssets::escape($failure['customMessage']) . '</div>')
            . '<div class="message">' . HtmlAssets::escape($failure['message']) . '</div>';

        if ($failure['diff'] !== null && count($failure['diff']) > 2) {
            $lines = ['<span class="fold">--- Expected  +++ Actual</span>'];
            foreach ($failure['diff'] as [$type, $text]) {
                $prefix = match ($type) {
                    'expected' => '- ',
                    'actual' => '+ ',
                    default => '  ',
                };
                $lines[] = '<span class="' . ($type === 'same' ? '' : $type) . '">' . HtmlAssets::escape($prefix . $text) . '</span>';
            }

            return $html . '<pre class="block diff">' . implode('', $lines) . '</pre>';
        }

        $values = '';
        foreach (['expected' => 'Expected', 'actual' => 'Actual'] as $key => $label) {
            if ($failure[$key] !== null) {
                $values .= "<span class=\"label\">$label</span><pre class=\"block\">" . HtmlAssets::escape($failure[$key]) . '</pre>';
            }
        }

        return $html . ($values === '' ? '' : "<div class=\"values\">$values</div>");
    }

    /** @param list<TestEntry> $tests */
    private static function skippedList(array $tests): string
    {
        $rows = '';
        foreach ($tests as $test) {
            $rows .= '<tr><td class="ch">' . self::channel($test['channel']) . '</td><td class="name">' . HtmlAssets::escape($test['suite'] . ' › ' . $test['name'])
                . '</td><td class="name">' . HtmlAssets::escape((string) $test['skipReason']) . '</td></tr>';
        }

        return "<table class=\"tests\">$rows</table>";
    }

    /** @param array{name: string, tests: list<TestEntry>} $suite */
    private static function suiteTable(array $suite): string
    {
        $rows = '';
        foreach ($suite['tests'] as $test) {
            $status = $test['status'];
            $time = $test['timeInSeconds'] === null ? '—' : number_format($test['timeInSeconds'] * 1000, 2) . ' ms';
            $rows .= '<tr><td class="ch">' . self::channel($test['channel']) . '</td>'
                . "<td class=\"state $status\"><span class=\"lamp\"></span>" . (self::VERDICTS[$status] ?? 'Not run') . '</td>'
                . '<td class="name">' . HtmlAssets::escape($test['name']) . "</td><td class=\"time\">$time</td></tr>";
        }

        return '<table class="tests"><caption>' . HtmlAssets::escape($suite['name']) . "</caption>$rows</table>";
    }

    private static function channel(int $channel): string
    {
        return 'CH ' . str_pad((string) $channel, 3, '0', STR_PAD_LEFT);
    }
}
