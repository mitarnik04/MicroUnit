<?php

namespace MicroUnit\Bootstrap;

use MicroUnit\Helpers\Filesystem;

/** Layout of the project-local runtime directory (.microunit by default). Git-ignores itself. */
final readonly class RuntimeDirectory
{
    public function __construct(
        public string $path,
    ) {}

    public function logs(): string
    {
        return $this->subdirectory('logs');
    }

    /** The few bytes the next run needs from this one (see LastRun). */
    public function lastRunFile(): string
    {
        return rtrim($this->path, '/\\') . DIRECTORY_SEPARATOR . 'last-run.json';
    }

    public function explorer(): string
    {
        return $this->subdirectory('explorer');
    }

    public function coverageCache(): string
    {
        return $this->subdirectory('cache/coverage');
    }

    public function opcache(): string
    {
        return $this->subdirectory('cache/opcache');
    }

    public function temporary(): string
    {
        return $this->subdirectory('tmp');
    }

    private function subdirectory(string $name): string
    {
        $directory = $this->path . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, $name);
        Filesystem::ensureDirectory($directory);

        $gitignore = $this->path . DIRECTORY_SEPARATOR . '.gitignore';
        if (!is_file($gitignore)) {
            file_put_contents($gitignore, "# Generated by MicroUnit: caches, run logs and explorer state.\n*\n");
        }

        return $directory;
    }
}
